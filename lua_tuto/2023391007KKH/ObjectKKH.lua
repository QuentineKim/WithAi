-- 5932 숫자사각형4-2
--정사각형의 한 변의 길이 n을 입력받은 후 다음과 같은 정사각형 형태로 출력하는 프로그램을 작성하시오.
-- 5
-- 1 2 3 4 5
-- 5 4 3 2 1
-- 1 2 3 4 5
-- 5 4 3 2 1
-- 1 2 3 4 5
--입력 : 정사각형 한 변의 길이 n을 입력받는다. (1≤n≤100)
local n = io.read("*n")
for i = 1, n do
    if i % 2 == 1 then
        for j = 1, n do
            io.write(j, " ")
        end
    else
        for j = n, 1, -1 do
            io.write(j, " ")
        end
    end
    io.write("\n")
end

