-- 1856 숫자사각형2
--사각형의 높이 n과 너비 m을 입력받은 후, 사각형 내부에 지그재그 형태로 1부터 n*m번까지 숫자가 차례대로 출력되는 프로그램을 작성하시오. 
--< 처리조건 > 
--숫자의 진행 순서는 처음에 왼쪽에서 오른쪽으로 너비 m만큼 진행 한 후 방향을 바꾸어서 이를 반복한다. 
local n, m = io.read("*n", "*n")
local num = 1
for i = 1, n do
    if i % 2 == 1 then
        for j = 1, m do
            io.write(num, " ")
            num = num + 1
        end
    else
        -- 짝수 행일 경우, 오른쪽에서 왼쪽으로 줄어들도록 출력
        local temp = num + m - 1
        for j = 1, m do
            io.write(temp, " ")
            temp = temp - 1
        end
        num = num + m -- 다음 행을 위해 num 증가
    end
    print()           -- 줄바꿈
end
